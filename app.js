async function processReceiptFile(file) {
  if (!file) return;
  if (!file.type.startsWith('image/')) {
    showToast('Выберите изображение чека');
    return;
  }
  if (file.size > 12 * 1024 * 1024) {
    showToast('Фото должно быть меньше 12 МБ');
    return;
  }
  if (scanObjectUrl) URL.revokeObjectURL(scanObjectUrl);
  scanObjectUrl = URL.createObjectURL(file);
  $('#scan-preview-image').src = scanObjectUrl;
  $('#scan-preview').hidden = false;
  $('#scan-results').hidden = true;
  $('#scan-progress').hidden = false;
  $('#scan-note').textContent = 'Первое распознавание загружает языковой модуль и может занять немного времени.';
  setScanProgress(8, 'Подготавливаем фотографию…');

  let worker;
  try {
    const TesseractLib = await loadTesseract();
    setScanProgress(18, 'Загружаем распознавание русского текста…');
    worker = await TesseractLib.createWorker(['rus', 'eng'], 1, {
      workerPath: 'https://cdn.jsdelivr.net/npm/tesseract.js@v5.0.0/dist/worker.min.js',
      corePath: 'https://cdn.jsdelivr.net/npm/tesseract.js-core@v5.0.0',
      langPath: 'https://tessdata.projectnaptha.com/4.0.0',
      logger: message => {
        const progress = Number.isFinite(message.progress) ? message.progress : 0;
        if (message.status === 'recognizing text') setScanProgress(30 + progress * 65, 'Читаем строки чека…');
        else if (message.status === 'loading language traineddata') setScanProgress(22 + progress * 8, 'Загружаем словарь…');
      }
    });
    const result = await worker.recognize(file, { rotateAuto: true });
    const products = findReceiptProducts(result.data.text);
    setScanProgress(100, products.length ? 'Готово — проверьте найденные продукты.' : 'Готово — совпадений не найдено.');
    renderScanResults(products, result.data.confidence);
    $('#scan-note').textContent = products.length ? 'Проверьте галочки: мы добавим выбранные продукты и сразу обновим рецепты.' : 'В каталоге пока нет совпадений с текстом чека. Попробуйте другой снимок.';
  } catch (error) {
    console.error(error);
    $('#scan-progress').hidden = true;
    $('#scan-results').hidden = false;
    renderScanResults([]);
    $('#scan-note').textContent = 'Не удалось загрузить OCR-модуль. Проверьте интернет и попробуйте ещё раз.';
  } finally {
    if (worker) await worker.terminate();
  }
}

