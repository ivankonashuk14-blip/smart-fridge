function normalizeReceiptText(value) {
  return String(value || '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[^\p{L}\p{N}]+/gu, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function findReceiptProducts(text) {
  const normalizedText = normalizeReceiptText(text);
  return Object.entries(receiptAliases)
    .filter(([, aliases]) => aliases.some(alias => normalizedText.includes(normalizeReceiptText(alias))))
    .map(([name]) => name)
    .filter(name => ingredientsCatalog.some(item => item.name === name));
}

